      <p>
        EBPM ツールの正しいつくり方・使い方は、<strong>「自分で作って、自分で使う」</strong>スタイルただ一つである。
        エビデンスは「作る側」と「使う側」が分断された瞬間に腐敗し始める。
        データ収集、可視化、運用のすべてを<strong>当事者が自らの手で</strong>行うべきである。
      </p>
      <p>
